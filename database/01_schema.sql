-- MySQL 8.0+ atau MariaDB 10.4+. Impor pada database BARU melalui phpMyAdmin.
-- Tidak ada DROP DATABASE/TABLE; data lama tidak dihapus otomatis.
CREATE DATABASE IF NOT EXISTS rsi_filkom CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE rsi_filkom;
CREATE TABLE PERUSAHAAN (
 idPerusahaan INT AUTO_INCREMENT PRIMARY KEY, namaPerusahaan VARCHAR(100) NOT NULL,
 alamat TEXT NOT NULL, emailPerusahaan VARCHAR(100) NOT NULL UNIQUE,
 statusVerifikasi VARCHAR(20) NOT NULL DEFAULT 'Menunggu', bidangUsaha VARCHAR(100) NOT NULL DEFAULT '',
 kontak VARCHAR(30) NOT NULL DEFAULT '', deskripsi TEXT, website VARCHAR(250) NOT NULL DEFAULT '',
 catatanVerifikasi TEXT, dihapusPada DATETIME NULL, dibuatPada DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE MAHASISWA (
 idMahasiswa INT AUTO_INCREMENT PRIMARY KEY,namaMahasiswa VARCHAR(100) NOT NULL,NIM VARCHAR(15) NOT NULL UNIQUE,
 email VARCHAR(100) NOT NULL UNIQUE,jurusan VARCHAR(50) NOT NULL,semester INT NOT NULL DEFAULT 1,
 IPK DECIMAL(3,2) NOT NULL DEFAULT 0,telepon VARCHAR(30) NOT NULL DEFAULT '',portofolio VARCHAR(250) NOT NULL DEFAULT '',
 bio TEXT,idCV INT NULL
) ENGINE=InnoDB;
CREATE TABLE AKUN (
 idAkun INT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(100) NOT NULL UNIQUE, email VARCHAR(100) NOT NULL UNIQUE,
 passwordHash VARCHAR(255) NOT NULL, namaPengguna VARCHAR(100) NOT NULL,
 role ENUM('Mahasiswa','Rekruter','Admin') NOT NULL, aktif TINYINT(1) NOT NULL DEFAULT 1,
 idMahasiswa INT NULL UNIQUE,idPerusahaan INT NULL,
 FOREIGN KEY(idMahasiswa) REFERENCES MAHASISWA(idMahasiswa), FOREIGN KEY(idPerusahaan) REFERENCES PERUSAHAAN(idPerusahaan),
 CONSTRAINT CK_AKUN_ROLE CHECK ((role='Mahasiswa' AND idMahasiswa IS NOT NULL AND idPerusahaan IS NULL) OR (role='Rekruter' AND idPerusahaan IS NOT NULL AND idMahasiswa IS NULL) OR (role='Admin' AND idMahasiswa IS NULL AND idPerusahaan IS NULL))
) ENGINE=InnoDB;
CREATE TABLE LOGIN_PERCOBAAN (kunci CHAR(64) PRIMARY KEY,jumlah INT NOT NULL DEFAULT 0,mulai DATETIME NOT NULL) ENGINE=InnoDB;
CREATE TABLE LOWONGAN (
 idLowongan INT AUTO_INCREMENT PRIMARY KEY,namaLowongan VARCHAR(100) NOT NULL,jenisPekerjaan VARCHAR(50) NOT NULL,
 modeKerja VARCHAR(50) NOT NULL,lokasiPenempatan VARCHAR(100) NOT NULL,tingkatSemesterMinimal INT NOT NULL,
 targetJurusan TEXT NOT NULL,deskripsi TEXT NOT NULL,dokumenPersyaratan TEXT NOT NULL,
 statusLowongan VARCHAR(20) NOT NULL DEFAULT 'Ditutup',tanggalDibuat DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,idPerusahaan INT NOT NULL,
 batasLamaran DATE NULL,kuota INT NOT NULL DEFAULT 1,durasiBulan INT NOT NULL DEFAULT 3,
 uangSaku DECIMAL(12,0) NOT NULL DEFAULT 0,konversiSKS INT NOT NULL DEFAULT 0,kualifikasi TEXT,dihapusPada DATETIME NULL,
 FOREIGN KEY(idPerusahaan) REFERENCES PERUSAHAAN(idPerusahaan), INDEX IDX_LOWONGAN_STATUS(statusLowongan,idPerusahaan)
) ENGINE=InnoDB;
CREATE TABLE `TAHAP SELEKSI` (
 idTahap INT AUTO_INCREMENT PRIMARY KEY,urutan INT NOT NULL,namaTahap VARCHAR(100) NOT NULL,keterangan TEXT,idLowongan INT NOT NULL,
 UNIQUE(idLowongan,urutan),UNIQUE(idTahap,idLowongan),FOREIGN KEY(idLowongan) REFERENCES LOWONGAN(idLowongan)
) ENGINE=InnoDB;
CREATE TABLE LAMARAN (
 idLamaran INT AUTO_INCREMENT PRIMARY KEY,dokumenPersyaratan TEXT NOT NULL,statusLamaran VARCHAR(50) NOT NULL DEFAULT 'Lamaran Terkirim',
 tanggalMelamar DATETIME NULL,idLowongan INT NOT NULL,idMahasiswa INT NOT NULL,idTahapSaatIni INT NULL,
 portofolio VARCHAR(250) NOT NULL DEFAULT '',suratPengantar TEXT,administrasiLolos TINYINT(1) NOT NULL DEFAULT 0,
 dibuatPada DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,UNIQUE(idMahasiswa,idLowongan),
 FOREIGN KEY(idLowongan) REFERENCES LOWONGAN(idLowongan),FOREIGN KEY(idMahasiswa) REFERENCES MAHASISWA(idMahasiswa),
 FOREIGN KEY(idTahapSaatIni,idLowongan) REFERENCES `TAHAP SELEKSI`(idTahap,idLowongan),
 UNIQUE(idLamaran,idLowongan)
) ENGINE=InnoDB;
CREATE TABLE DOKUMEN (
 idDokumen INT AUTO_INCREMENT PRIMARY KEY,idAkun INT NOT NULL,namaAsli VARCHAR(250) NOT NULL,namaInternal VARCHAR(100) NOT NULL UNIQUE,
 ukuran INT NOT NULL,mime VARCHAR(80) NOT NULL DEFAULT 'application/pdf',dibuatPada DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(idAkun) REFERENCES AKUN(idAkun)
) ENGINE=InnoDB;
ALTER TABLE MAHASISWA ADD CONSTRAINT FK_CV FOREIGN KEY(idCV) REFERENCES DOKUMEN(idDokumen);
CREATE TABLE DOKUMEN_PERUSAHAAN (
 id INT AUTO_INCREMENT PRIMARY KEY,idPerusahaan INT NOT NULL,idDokumen INT NOT NULL,namaDokumen VARCHAR(100) NOT NULL,
 hasilPemeriksaan VARCHAR(30) NOT NULL DEFAULT 'Belum diperiksa',catatan TEXT,idPemeriksa INT NULL,
 FOREIGN KEY(idPerusahaan) REFERENCES PERUSAHAAN(idPerusahaan),FOREIGN KEY(idDokumen) REFERENCES DOKUMEN(idDokumen),FOREIGN KEY(idPemeriksa) REFERENCES AKUN(idAkun)
) ENGINE=InnoDB;
CREATE TABLE HASIL_SELEKSI (
 idHasil INT AUTO_INCREMENT PRIMARY KEY,idLamaran INT NOT NULL,idTahap INT NOT NULL,idLowongan INT NOT NULL,
 hasil VARCHAR(30) NOT NULL,catatan TEXT,idPenilai INT NOT NULL,diperbaruiPada DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(idLamaran,idTahap),FOREIGN KEY(idLamaran,idLowongan) REFERENCES LAMARAN(idLamaran,idLowongan),
 FOREIGN KEY(idTahap,idLowongan) REFERENCES `TAHAP SELEKSI`(idTahap,idLowongan),FOREIGN KEY(idPenilai) REFERENCES AKUN(idAkun)
) ENGINE=InnoDB;
CREATE TABLE NOTIFIKASI (
 idNotifikasi INT AUTO_INCREMENT PRIMARY KEY,idPenerima INT NOT NULL,judul VARCHAR(150) NOT NULL,isi TEXT NOT NULL,
 tautan VARCHAR(250) NOT NULL,sudahDibaca TINYINT(1) NOT NULL DEFAULT 0,dibuatPada DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(idPenerima) REFERENCES AKUN(idAkun),INDEX IDX_NOTIF(idPenerima,sudahDibaca)
) ENGINE=InnoDB;
CREATE TABLE PESAN_CHAT (
 idPesan INT AUTO_INCREMENT PRIMARY KEY,idLamaran INT NOT NULL,idPengirim INT NOT NULL,isi TEXT NOT NULL,
 dikirimPada DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(idLamaran) REFERENCES LAMARAN(idLamaran),FOREIGN KEY(idPengirim) REFERENCES AKUN(idAkun)
) ENGINE=InnoDB;
CREATE TABLE JADWAL_SELEKSI (
 idJadwal INT AUTO_INCREMENT PRIMARY KEY,idLamaran INT NOT NULL,idTahap INT NOT NULL,idLowongan INT NOT NULL,
 judul VARCHAR(150) NOT NULL,waktu DATETIME NOT NULL,tautan VARCHAR(250) NOT NULL DEFAULT '',lokasi VARCHAR(150) NOT NULL DEFAULT '',catatan TEXT,
 UNIQUE(idLamaran,idTahap),FOREIGN KEY(idLamaran,idLowongan) REFERENCES LAMARAN(idLamaran,idLowongan),
 FOREIGN KEY(idTahap,idLowongan) REFERENCES `TAHAP SELEKSI`(idTahap,idLowongan)
) ENGINE=InnoDB;
CREATE TABLE PENGINGAT (
 idPengingat INT AUTO_INCREMENT PRIMARY KEY,idAkun INT NOT NULL,idLamaran INT NULL,judul VARCHAR(150) NOT NULL,waktu DATETIME NOT NULL,
 catatan TEXT,diingatkanPada DATETIME NULL,FOREIGN KEY(idAkun) REFERENCES AKUN(idAkun),FOREIGN KEY(idLamaran) REFERENCES LAMARAN(idLamaran)
) ENGINE=InnoDB;
CREATE TABLE RIWAYAT_VERIFIKASI (
 idVerifikasi INT AUTO_INCREMENT PRIMARY KEY,idPerusahaan INT NOT NULL,idAdmin INT NOT NULL,hasil VARCHAR(30) NOT NULL,
 catatan TEXT NOT NULL,dibuatPada DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(idPerusahaan) REFERENCES PERUSAHAAN(idPerusahaan),FOREIGN KEY(idAdmin) REFERENCES AKUN(idAkun)
) ENGINE=InnoDB;
